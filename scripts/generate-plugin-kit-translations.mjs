import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Builds `src/translations/en/plugin-kit.php` from the English strings Plugin Kit publishes, so Verbb Base can register
// the shared `plugin-kit` category. Pass the JSON path to read a local Plugin Kit checkout, otherwise the installed
// `@verbb/plugin-kit-web` is used. `--check` reports a stale file without rewriting it.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/translations/en/plugin-kit.php');
const args = process.argv.slice(2);
const check = args.includes('--check');
const sourceArg = args.find((arg) => !arg.startsWith('--'));

let sourcePath;

try {
    sourcePath = sourceArg
        ? path.resolve(sourceArg)
        : createRequire(import.meta.url).resolve('@verbb/plugin-kit-web/translations/plugin-kit.json');
} catch {
    console.error('Install @verbb/plugin-kit-web or pass the path to its translations/plugin-kit.json.');
    process.exit(1);
}

const source = JSON.parse(await fs.readFile(sourcePath, 'utf8'));

if (source.category !== 'plugin-kit' || !Array.isArray(source.messages)) {
    console.error(`${sourcePath} isn't a Plugin Kit translation list.`);
    process.exit(1);
}

const quote = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lines = source.messages.map((message) => `    ${quote(message)} => ${quote(message)},`);
const contents = `<?php

// Generated by \`npm run translations:plugin-kit\` from @verbb/plugin-kit-web/translations/plugin-kit.json. Don't edit.
// Plugin Kit's English strings, which are also their keys. Translate them in a site's translations/<language>/plugin-kit.php.

return [
${lines.join('\n')}
];
`;

if (check) {
    const current = await fs.readFile(outputPath, 'utf8').catch(() => '');

    if (current !== contents) {
        console.error(`${path.relative(root, outputPath)} doesn't match ${sourcePath}. Run \`npm run translations:plugin-kit\`.`);
        process.exit(1);
    }

    console.log(`${path.relative(root, outputPath)} matches ${sourcePath}.`);
} else {
    await fs.mkdir(path.dirname(outputPath), { recursive: true });
    await fs.writeFile(outputPath, contents, 'utf8');
    console.log(`Generated ${path.relative(root, outputPath)} with ${source.messages.length} strings.`);
}
